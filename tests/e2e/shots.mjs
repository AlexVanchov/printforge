// Visual review screenshots: node tests/e2e/shots.mjs <outdir> [chromium|webkit] [dark]
import { chromium, webkit } from 'playwright';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const out = process.argv[2] || '/tmp';
const which = process.argv[3] || 'chromium';
const dark = process.argv[4] === 'dark';
const PORT = 9900 + Math.floor(Math.random() * 90);
const HOME = fs.mkdtempSync(path.join(os.tmpdir(), 'pf-shots-'));
fs.mkdirSync(path.join(HOME, 'Documents'), { recursive: true });
fs.mkdirSync(path.join(HOME, '.config/printforge'), { recursive: true });
fs.writeFileSync(path.join(HOME, '.config/printforge/settings.json'), JSON.stringify({ welcomed: true, printer: 'bambu_a1', material: 'pla', units: 'mm' }));
const srv = spawn(process.env.PF_BIN || 'build/printforge', ['--serve', String(PORT)], { env: { ...process.env, HOME }, stdio: 'ignore' });
process.on('exit', () => srv.kill());
await new Promise((r) => setTimeout(r, 500));
const b = await (which === 'webkit' ? webkit : chromium).launch();
const page = await b.newPage({ viewport: { width: +(process.env.VW || 1440), height: +(process.env.VH || 900) }, colorScheme: dark ? 'dark' : 'light' });
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
const settle = async () => { await page.waitForFunction(() => window.printforge && !window.printforge.model.updating && !document.body.classList.contains('busy')); await page.waitForTimeout(500); };
const shot = (n) => page.screenshot({ path: `${out}/${dark ? 'dark-' : ''}${n}.png` });
await page.goto(`http://localhost:${PORT}/`);
await page.waitForSelector('#splash', { state: 'detached' });
await shot('10-empty');
await page.click('[data-testid=tab-functional]');
await page.click('[data-testid=add-gear]');
await settle();
await shot('11-gear');
await page.click('[data-testid=add-storage_box]');
await settle();
await page.evaluate(() => window.printforge.inspector.root.scrollTop = 700);
await page.waitForTimeout(200);
await shot('12-storage-params');
await page.click('[data-testid=tab-basic]');
await page.click('[data-testid=add-cylinder]');
await settle();
const sb = await page.evaluate(() => window.printforge.model.objects.find((o) => o.kind === 'storage_box').id);
await page.evaluate(async (id) => {
  const m = window.printforge.model;
  const sbx = m.byId(id);
  const b = await m.worldBox(sbx);
  const c = m.selected()[0];
  await m.setPosition([c], 0, (b.min[0] + b.max[0]) / 2);
  await m.setPosition([c], 1, (b.min[1] + b.max[1]) / 2);
  await m.setHole([c], true);
}, sb);
await settle();
await page.click('[data-testid=view-fit]');
await page.waitForTimeout(600);
await shot('13-hole');
await page.click('[data-testid=tool-rotate]');
await page.waitForTimeout(300);
await shot('14-rotate');
await page.click('[data-testid=tool-select]');
await page.click('[data-testid=check-toggle]');
await page.waitForTimeout(300);
await shot('15-check-open');
await page.click('[data-testid=btn-export]');
await page.waitForTimeout(300);
await shot('16-export');
await page.keyboard.press('Escape');
await page.click('[data-testid=btn-open]');
await page.waitForTimeout(500);
await shot('17-open');
await page.keyboard.press('Escape');
await page.click('[data-testid=btn-settings]');
await page.waitForTimeout(300);
await shot('18-settings');
await page.keyboard.press('Escape');
await page.click('[data-testid=btn-help]');
await page.waitForTimeout(300);
await shot('19-help');
await page.keyboard.press('Escape');
console.log(errs.length ? errs.join('\n') : 'no page errors');
await b.close();
srv.kill();
