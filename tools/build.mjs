// Build PrintForge:
//   1. bundle web/src with esbuild (one IIFE, minified)
//   2. inline CSS, the geometry kernel's wasm (base64) and the text font
//      into a single HTML page  -> build/printforge.html
//   3. emit that page as a Solemn module  -> app/assets.slm
//   4. (unless --web-only) compile the app with the Solemn toolchain
//      -> build/printforge   (release build; contracts verified by check)
//
// Usage: node tools/build.mjs [--web-only] [--debug] [--solemn <path>] [--out <file>]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const opt = (n, d) => {
  const i = args.indexOf(n);
  return i >= 0 ? args[i + 1] : d;
};
let solemn = opt('--solemn', process.env.SOLEMN || 'solemn');
if (solemn.includes('/')) solemn = path.resolve(solemn);
const out = path.resolve(root, opt('--out', 'build/printforge'));
fs.mkdirSync(path.join(root, 'build'), { recursive: true });

const t0 = Date.now();
const bundle = await esbuild.build({
  entryPoints: [path.join(root, 'web/src/main.js')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['safari15', 'chrome100', 'firefox100'],
  minify: !flag('--debug'),
  write: false,
  charset: 'ascii',
  legalComments: 'none',
  external: ['node:module'],
  logOverride: { 'empty-import-meta': 'silent' },
});
let js = bundle.outputFiles[0].text;
js = js.replace(/<\/script/gi, '<\\/script');

const css = fs.readFileSync(path.join(root, 'web/styles/app.css'), 'utf8');
const wasm = fs.readFileSync(path.join(root, 'node_modules/manifold-3d/manifold.wasm')).toString('base64');
const font = JSON.stringify(JSON.parse(fs.readFileSync(path.join(root, 'node_modules/three/examples/fonts/droid/droid_sans_bold.typeface.json'), 'utf8')));
let html = fs.readFileSync(path.join(root, 'web/index.html'), 'utf8');
html = html
  .replace('/*CSS*/', () => css)
  .replace('<!--DATA-->', () => `<script>window.__PF_WASM__="${wasm}";window.__PF_FONT__=${font};</script>`)
  .replace('<!--JS-->', () => `<script>${js}</script>`);
fs.writeFileSync(path.join(root, 'build/printforge.html'), html);

// ---- Solemn module ---------------------------------------------------------
// Text literals allow only \n \t \" \\ escapes, so other control characters
// must not appear; split into chunks joined at runtime.
if (/[\x00-\x08\x0b-\x1f\x7f]/.test(html.replace(/\r/g, ''))) throw new Error('page contains control characters that cannot be embedded');
html = html.replace(/\r/g, '');
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t');
const CHUNK = 60000;
const chunks = [];
for (let i = 0; i < html.length; i += CHUNK) {
  let end = Math.min(html.length, i + CHUNK);
  // never split a UTF-16 surrogate pair
  if (end < html.length && /[\ud800-\udbff]/.test(html[end - 1])) end--;
  chunks.push(html.slice(i, end));
  i = end - CHUNK;
}
let slm = '# GENERATED by tools/build.mjs — do not edit. The whole front end (HTML,\n# CSS, JS, the geometry kernel\'s WebAssembly and the font) as one Text.\n\n';
slm += 'fn page() -> Text {\n  return ' + join(0, chunks.length) + '\n}\n';
function join(lo, hi) {
  if (hi - lo === 1) return `chunk${lo}()`;
  const mid = (lo + hi) >> 1;
  return '(' + join(lo, mid) + ' + ' + join(mid, hi) + ')';
}
chunks.forEach((c, i) => {
  slm += `\nfn chunk${i}() -> Text {\n  return "${esc(c)}"\n}\n`;
});
fs.writeFileSync(path.join(root, 'app/assets.slm'), slm);
console.log(`web: ${(js.length / 1024).toFixed(0)} KB js, page ${(html.length / 1024).toFixed(0)} KB in ${chunks.length} chunks (${Date.now() - t0} ms)`);

if (!flag('--web-only')) {
  const t1 = Date.now();
  const run = (a) => execFileSync(solemn, a, { cwd: path.join(root, 'app'), stdio: 'inherit' });
  run(['check', 'main.slm']);
  run(['build', 'main.slm', '-o', out, ...(flag('--debug') ? [] : ['--release'])]);
  console.log(`solemn: checked + built ${path.relative(root, out)} (${Date.now() - t1} ms)`);
}
